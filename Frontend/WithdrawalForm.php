	}

	/**
	 * Posted entry point (form, account, email_link).
	 *
	 * @return string
	 */
	private function posted_via(): string {
		// phpcs:ignore WordPress.Security.NonceVerification.Missing -- Verified in handle().
		$via = isset( $_POST['ppwb_via'] ) ? sanitize_key( wp_unslash( $_POST['ppwb_via'] ) ) : 'form';

		return in_array( $via, array( 'form', 'account', 'email_link' ), true ) ? $via : 'form';
	}

	/**
	 * Order from a My account link, only for its logged-in owner.
	 *
	 * @param string $value "orderId.signature".
	 * @return WC_Order|null
	 */
	private function order_from_account_link( string $value ): ?WC_Order {
		$parts   = explode( '.', $value, 2 );
		$user_id = get_current_user_id();
		if ( 2 !== count( $parts ) || 0 === $user_id || ! hash_equals( $this->tokens->sign( 'account|' . absint( $parts[0] ) . '|' . $user_id ), $parts[1] ) ) {
			return null;
		}

		$order = wc_get_order( absint( $parts[0] ) );

		return $order instanceof WC_Order && $order->get_customer_id() === $user_id ? $order : null;
	}

	/**
	 * Orders of the logged-in customer that can still be withdrawn.
	 *
	 * @return list<array{number: string, date: string, url: string}>
	 */
	private function my_orders(): array {
		$user_id = get_current_user_id();
		if ( 0 === $user_id ) {
			return array();
		}

		$orders = wc_get_orders(
			array(
				'customer_id' => $user_id,
				'limit'       => 20,
				'orderby'     => 'date',
				'order'       => 'DESC',
			)
		);

		$list = array();
		foreach ( is_array( $orders ) ? $orders : array() as $order ) {
			if ( ! $order instanceof WC_Order || null !== $this->service->blocking_reason( $order ) ) {
				continue;
			}
			$created = $order->get_date_created();
			$list[]  = array(
				'number' => (string) $order->get_order_number(),
				'date'   => null === $created ? '' : Dates::date( $created ),
				'url'    => add_query_arg( 'ppwb_account', $order->get_id() . '.' . $this->tokens->sign( 'account|' . $order->get_id() . '|' . $user_id ), $this->form_url() ),
			);
		}

		return $list;
	}

	/**
	 * Optional reason, limited to 1000 characters.
