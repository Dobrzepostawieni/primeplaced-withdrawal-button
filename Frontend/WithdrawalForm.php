<?php
/**
 * Withdrawal form: [ppwb_form] shortcode, step handling and footer link.
 *
 * @package PrimePlaced\WithdrawalButton
 */

namespace PrimePlaced\WithdrawalButton\Frontend;

use DateTimeImmutable;
use PrimePlaced\WithdrawalButton\Data\RequestRepository;
use PrimePlaced\WithdrawalButton\Data\Settings;
use PrimePlaced\WithdrawalButton\Domain\Iban;
use PrimePlaced\WithdrawalButton\Domain\Money;
use PrimePlaced\WithdrawalButton\Engine\Module;
use PrimePlaced\WithdrawalButton\Integrations\Dates;
use PrimePlaced\WithdrawalButton\Integrations\RateLimiter;
use PrimePlaced\WithdrawalButton\Integrations\WithdrawalBlocked;
use PrimePlaced\WithdrawalButton\Integrations\WithdrawalService;
use Throwable;
use WC_Order;

/**
 * Class WithdrawalForm
 *
 * Steps are full page loads (POST, then a redirect after the final step), so
 * the form works without JavaScript.
 */
final class WithdrawalForm implements Module {

	private const NONCE = 'ppwb_form';

	private const MAX_FAILED_LOOKUPS = 5;

	private const LOOKUP_WINDOW = 900;

	private const CLEANUP_HOOK = 'ppwb_cleanup_submission_lock';

	/**
	 * View prepared by the POST handler for the shortcode.
	 *
	 * @var array<string, mixed>
	 */
	private array $view = array( 'step' => 'lookup' );

	/**
	 * Creates the module.
	 *
	 * @param WithdrawalService $service  Withdrawal use cases.
	 * @param RequestRepository $requests Request storage.
	 * @param Settings          $settings Plugin settings.
	 * @param FormToken         $tokens   Step tokens.
	 * @param RateLimiter       $limiter  Lookup rate limiter.
	 */
	public function __construct(
		private WithdrawalService $service,
		private RequestRepository $requests,
		private Settings $settings,
		private FormToken $tokens,
		private RateLimiter $limiter
	) {
	}

	/**
	 * Adds the shortcode, the POST handler, the footer link and styles.
	 *
	 * @return void
	 */
	public function register(): void {
		add_shortcode( 'ppwb_form', array( $this, 'render' ) );
		add_action( 'template_redirect', array( $this, 'handle' ) );
		add_action( 'wp_footer', array( $this, 'footer_link' ), 5 );
		add_action( 'wp_enqueue_scripts', array( $this, 'styles' ) );
		add_action(
			self::CLEANUP_HOOK,
			static function ( string $lock ): void {
				delete_option( $lock );
			}
		);
	}

	/**
	 * URL of the form page.
	 *
	 * @return string
	 */
	public function form_url(): string {
		$page_id = $this->settings->form_page_id();
		$url     = $page_id > 0 ? get_permalink( $page_id ) : false;

		return is_string( $url ) ? $url : home_url( '/' );
	}

	/**
	 * Prints the "Withdraw from contract here" link in the footer.
	 *
	 * @return void
	 */
	public function footer_link(): void {
		if ( $this->settings->form_page_id() <= 0 || ! $this->settings->flag( 'button_in_footer' ) ) {
			return;
		}

		printf(
			'<div class="ppwb-footer"><a class="ppwb-footer__link" href="%1$s"><span aria-hidden="true">&#8617;</span> %2$s</a></div>',
			esc_url( $this->form_url() ),
			esc_html( $this->settings->button_label() )
		);
	}

	/**
	 * Adds the small inline stylesheet; the form inherits theme typography.
	 *
	 * @return void
	 */
	public function styles(): void {
		wp_register_style( 'ppwb-front', false, array(), PPWB_VERSION );
		wp_enqueue_style( 'ppwb-front' );
		$css = (string) file_get_contents( PPWB_PLUGIN_ROOT . 'assets/front/form.css' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local plugin file.
		wp_add_inline_style( 'ppwb-front', $css );

		$asset_file = PPWB_PLUGIN_ROOT . 'assets/build/ppwb-form.asset.php';
		$pages      = array_filter( array( $this->settings->form_page_id(), (int) get_option( StatusPage::PAGE_OPTION, 0 ) ) );
		if ( array() === $pages || ! is_page( $pages ) || ! is_readable( $asset_file ) ) {
			return;
		}

		/**
		 * Asset metadata generated by wp-scripts.
		 *
		 * @var array{dependencies: list<string>, version: string} $asset
		 */
		$asset = require $asset_file;
		wp_enqueue_script(
			'ppwb-form',
			plugins_url( 'assets/build/ppwb-form.js', PPWB_PLUGIN_ABSOLUTE ),
			$asset['dependencies'],
			$asset['version'],
			array(
				'in_footer' => true,
				'strategy'  => 'defer',
			)
		);
	}

	/**
	 * Processes a submitted step before any output.
	 *
	 * @return void
	 */
	public function handle(): void {
		$page_id = $this->settings->form_page_id();
		if ( $page_id <= 0 || ! is_page( $page_id ) ) {
			return;
		}

		// phpcs:disable WordPress.Security.NonceVerification.Recommended -- Signed request ID, read-only view.
		if ( isset( $_GET['ppwb_done'] ) ) {
			$this->view = $this->success_view( sanitize_text_field( wp_unslash( $_GET['ppwb_done'] ) ) );
			return;
		}

		// Entry from the "Completed order" email link or from My account: step 1 is skipped.
		$entry = null;
		$via   = 'form';
		if ( isset( $_GET['ppwb_ot'] ) ) {
			$entry = MyAccount::order_from_email_token( sanitize_text_field( wp_unslash( $_GET['ppwb_ot'] ) ), $this->tokens );
			$via   = 'email_link';
		} elseif ( isset( $_GET['ppwb_account'] ) ) {
			$entry = $this->order_from_account_link( sanitize_text_field( wp_unslash( $_GET['ppwb_account'] ) ) );
			$via   = 'account';
		}
		// phpcs:enable

		if ( 'form' !== $via && ( ! isset( $_SERVER['REQUEST_METHOD'] ) || 'POST' !== $_SERVER['REQUEST_METHOD'] ) ) {
			$this->view = null === $entry
				? array(
					'step'  => 'lookup',
					'error' => __( 'This link is not valid any more. Enter the order number and email.', 'primeplaced-withdrawal-button' ),
				)
				: $this->products_view( $entry, $this->tokens->issue( $entry->get_id(), $entry->get_billing_email() ), null, '', '', $via );
			return;
		}

		if ( ! isset( $_SERVER['REQUEST_METHOD'] ) || 'POST' !== $_SERVER['REQUEST_METHOD'] || ! isset( $_POST['ppwb_action'] ) ) {
			return;
		}

		$nonce = isset( $_POST['_ppwb_nonce'] ) ? sanitize_text_field( wp_unslash( $_POST['_ppwb_nonce'] ) ) : '';
		if ( ! wp_verify_nonce( $nonce, self::NONCE ) ) {
			$this->view = array(
				'step'  => 'lookup',
				'error' => __( 'The form has expired. Please start again.', 'primeplaced-withdrawal-button' ),
			);
			return;
		}

		$action = sanitize_key( wp_unslash( $_POST['ppwb_action'] ) );
		$token  = isset( $_POST['ppwb_token'] ) ? sanitize_text_field( wp_unslash( $_POST['ppwb_token'] ) ) : '';

		$this->view = match ( $action ) {
			'lookup'   => $this->lookup(
				isset( $_POST['ppwb_order'] ) ? sanitize_text_field( wp_unslash( $_POST['ppwb_order'] ) ) : '',
				isset( $_POST['ppwb_email'] ) ? sanitize_email( wp_unslash( $_POST['ppwb_email'] ) ) : ''
			),
			// "Back" from step 3 keeps the chosen quantities and the reason.
			'products' => $this->with_order( $token, fn ( WC_Order $order ) => $this->products_view( $order, $token, array() === $this->posted_selection() ? null : $this->posted_selection(), $this->posted_reason() ) ),
			'summary'  => $this->with_order( $token, fn ( WC_Order $order ) => $this->summary( $order, $token, $this->posted_selection(), $this->posted_reason() ) ),
			'confirm'  => $this->with_order( $token, fn ( WC_Order $order ) => $this->confirm( $order, $token ) ),
			default    => array( 'step' => 'lookup' ),
		};
	}

	/**
	 * Renders the current step.
	 *
	 * @return string
	 */
	public function render(): string {
		$view = $this->view + array(
			'form_url'  => $this->form_url(),
			'nonce'     => wp_nonce_field( self::NONCE, '_ppwb_nonce', false, false ),
			'days'      => $this->settings->withdrawal_period()->days(),
			'error'     => '',
			'my_orders' => 'lookup' === ( $this->view['step'] ?? 'lookup' ) ? $this->my_orders() : array(),
		);

		$step = is_string( $view['step'] ) ? $view['step'] : 'lookup';

		ob_start();
		Templates::render( 'form/' . $step, $view );

		return (string) ob_get_clean();
	}

	/**
	 * Step 1: verifies order number and email.
	 *
	 * @param string $order_number Order number.
	 * @param string $email        Email.
	 * @return array<string, mixed>
	 */
	private function lookup( string $order_number, string $email ): array {
		$limiter_key = 'lookup|' . $this->client_ip();
		if ( $this->limiter->is_blocked( $limiter_key, self::MAX_FAILED_LOOKUPS ) ) {
			return array(
				'step'  => 'lookup',
				'error' => __( 'Too many attempts. Please try again in a few minutes.', 'primeplaced-withdrawal-button' ),
			);
		}

		$order = $this->service->find_order( $order_number, $email );
		if ( null === $order ) {
			$this->limiter->hit( $limiter_key, self::LOOKUP_WINDOW );
			return array(
				'step'         => 'lookup',
				'error'        => __( 'We could not find an order for these details. Check the number and the email address.', 'primeplaced-withdrawal-button' ),
				'order_number' => $order_number,
				'email'        => $email,
			);
		}

		return $this->products_view( $order, $this->tokens->issue( $order->get_id(), $email ) );
	}

	/**
	 * Step 2: product selection, or a message when the order cannot be withdrawn.
	 *
	 * @param WC_Order             $order     Order.
	 * @param string               $token     Step token.
	 * @param array<int, int>|null $selection Previous selection, all available when null.
	 * @param string               $reason    Previous reason.
	 * @param string               $error     Error to show.
	 * @param string               $via       Entry point; '' reads the posted one.
	 * @return array<string, mixed>
	 */
	private function products_view( WC_Order $order, string $token, ?array $selection = null, string $reason = '', string $error = '', string $via = '' ): array {
		$blocking = $this->service->blocking_reason( $order );
		if ( null !== $blocking ) {
			return $this->blocked_view( $blocking );
		}

		$lines = $this->service->lines( $order );
		if ( null === $selection ) {
			$selection = array_column( $lines, 'available', 'id' );
		}

		return array(
			'step'         => 'products',
			'token'        => $token,
			'order_number' => $order->get_order_number(),
			'lines'        => $this->display_lines( $order, $lines ),
			// Estimate for the preselected quantities; step 3 shows the exact amount.
			'estimate'     => wc_price( (float) Money::to_decimal( $this->service->estimated_refund_minor( $order, $this->service->valid_selection( $order, $selection ) ), wc_get_price_decimals() ), array( 'currency' => $order->get_currency() ) ),
			'selection'    => $selection,
			'reason'       => $reason,
			'reason_code'  => $this->posted_reason_code(),
			'reasons'      => $this->settings->return_reasons(),
			'error'        => $error,
			'needs_bank'   => $this->service->needs_bank_account( $order ),
			'pay_method'   => $order->get_payment_method_title(),
			'iban'         => $this->posted_iban(),
			'via'          => '' === $via ? $this->posted_via() : $via,
			'notice'       => $this->before_shipment_notice( $order ),
			'ask_consumer' => $this->service->asks_consumer_status( $order ),
			'consumer'     => $this->posted_consumer(),
		);
	}

	/**
	 * Step 3: summary with the full statement text.
	 *
	 * @param WC_Order        $order     Order.
	 * @param string          $token     Step token.
	 * @param array<int, int> $selection Posted selection.
	 * @param string          $reason    Posted reason.
	 * @return array<string, mixed>
	 */
	private function summary( WC_Order $order, string $token, array $selection, string $reason ): array {
		$valid = $this->service->valid_selection( $order, $selection );
		if ( array() === $valid ) {
			return $this->products_view( $order, $token, $selection, $reason, __( 'Choose at least one product.', 'primeplaced-withdrawal-button' ) );
		}

		if ( $this->service->asks_consumer_status( $order ) && ! $this->posted_consumer() ) {
			return $this->products_view( $order, $token, $selection, $reason, __( 'Confirm that you bought as a consumer or as a sole trader with consumer rights.', 'primeplaced-withdrawal-button' ) );
		}

		$iban = $this->posted_iban();
		if ( $this->service->needs_bank_account( $order ) && ! Iban::is_valid( $iban ) ) {
			return $this->products_view( $order, $token, $selection, $reason, __( 'Enter a valid bank account number (IBAN) for the refund.', 'primeplaced-withdrawal-button' ) );
		}

		$full_name = trim( $order->get_formatted_billing_full_name() );
		$chosen    = array();
		foreach ( $this->display_lines( $order, $this->service->lines( $order ) ) as $line ) {
			if ( isset( $valid[ $line['id'] ] ) ) {
				$chosen[] = $line + array( 'qty' => $valid[ $line['id'] ] );
			}
		}

		return array(
			'step'          => 'summary',
			'token'         => $token,
			'selection'     => $valid,
			'reason'        => $reason,
			'reason_code'   => $this->posted_reason_code(),
			'full_name'     => $full_name,
			'email'         => $order->get_billing_email(),
			'contact_email' => '' !== $this->posted_contact_email() ? $this->posted_contact_email() : $order->get_billing_email(),
			'chosen'        => $chosen,
			'total'         => wc_price( (float) Money::to_decimal( $this->service->estimated_refund_minor( $order, $valid ), wc_get_price_decimals() ), array( 'currency' => $order->get_currency() ) ),
			'statement'     => $this->service->statement_text( $order, $valid, $full_name, null ),
			'submission'    => wp_generate_uuid4(),
			'iban'          => '' === $iban ? '' : Iban::normalize( $iban ),
			'via'           => $this->posted_via(),
			'notice'        => $this->before_shipment_notice( $order ),
			'consumer'      => $this->posted_consumer(),
		);
	}

	/**
	 * Final step: stores the statement once and redirects to the success view.
	 *
	 * @param WC_Order $order Order.
	 * @param string   $token Step token.
	 * @return array<string, mixed>
	 */
	private function confirm( WC_Order $order, string $token ): array {
		// phpcs:disable WordPress.Security.NonceVerification.Missing -- Verified in handle().
		$submission = isset( $_POST['ppwb_submission'] ) ? sanitize_key( wp_unslash( $_POST['ppwb_submission'] ) ) : '';
		$full_name  = isset( $_POST['ppwb_full_name'] ) ? sanitize_text_field( wp_unslash( $_POST['ppwb_full_name'] ) ) : '';
		// phpcs:enable

		if ( '' === $full_name ) {
			$view          = $this->summary( $order, $token, $this->posted_selection(), $this->posted_reason() );
			$view['error'] = __( 'Enter your full name.', 'primeplaced-withdrawal-button' );
			return $view;
		}
		if ( '' === $this->posted_contact_email() ) {
			$view          = $this->summary( $order, $token, $this->posted_selection(), $this->posted_reason() );
			$view['error'] = __( 'Enter a valid email address for the confirmation.', 'primeplaced-withdrawal-button' );
			return $view;
		}

		if ( $this->service->asks_consumer_status( $order ) && ! $this->posted_consumer() ) {
			return $this->products_view( $order, $token, $this->posted_selection(), $this->posted_reason(), __( 'Confirm that you bought as a consumer or as a sole trader with consumer rights.', 'primeplaced-withdrawal-button' ) );
		}

		// The summary step checked the account already; a POST sent straight to
		// "confirm" must not store a request without one.
		if ( $this->service->needs_bank_account( $order ) && ! Iban::is_valid( $this->posted_iban() ) ) {
			return $this->products_view( $order, $token, $this->posted_selection(), $this->posted_reason(), __( 'Enter a valid bank account number (IBAN) for the refund.', 'primeplaced-withdrawal-button' ) );
		}

		// A double click sends the same submission key twice: the second POST
		// waits for the first and is redirected to the same request.
		$lock = 'ppwb_submission_' . $submission;
		if ( '' === $submission || ! add_option( $lock, 0, '', false ) ) {
			// The first POST stores the statement, then sends the email with the
			// PDF, which can take several seconds: wait up to 20 s for its ID.
			for ( $i = 0; '' !== $submission && $i < 80; $i++ ) {
				wp_cache_delete( $lock, 'options' );
				wp_cache_delete( 'notoptions', 'options' );
				$existing = (int) get_option( $lock, 0 );
				if ( $existing > 0 ) {
					$this->redirect_to_success( $existing );
				}
				usleep( 250000 );
			}
			return array(
				'step'    => 'message',
				'title'   => __( 'Your statement is being saved', 'primeplaced-withdrawal-button' ),
				'message' => __( 'We received the form already. Do not send it again: the confirmation with the request number will reach your email in a moment.', 'primeplaced-withdrawal-button' ),
			);
		}

		// Publish the ID as soon as the request row exists, before the emails
		// and the PDF, so a second click finds it at once.
		$publish = static function ( int $request_id ) use ( $lock ): void {
			update_option( $lock, $request_id, false );
		};
		add_action( 'ppwb_request_created', $publish, 0 );

		try {
			$iban       = $this->service->needs_bank_account( $order ) ? Iban::normalize( $this->posted_iban() ) : '';
			$request_id = $this->service->submit( $order, $this->posted_selection(), $full_name, $this->posted_reason(), $this->client_ip(), $iban, $this->posted_via(), $this->posted_reason_code(), $this->posted_contact_email() );
		} catch ( WithdrawalBlocked $blocked ) {
			delete_option( $lock );
			return $this->blocked_view( $blocked->reason );
		} catch ( Throwable $error ) {
			delete_option( $lock );
			// phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log -- Submission failures must reach the server log.
			error_log( '[primeplaced-withdrawal-button] Submission failed: ' . $error->getMessage() );
			$view          = $this->summary( $order, $token, $this->posted_selection(), $this->posted_reason() );
			$view['error'] = __( 'We could not save your statement. Please try again.', 'primeplaced-withdrawal-button' );
			return $view;
		}

		remove_action( 'ppwb_request_created', $publish, 0 );
		if ( $this->service->asks_consumer_status( $order ) ) {
			$this->requests->set_flag( $request_id, 'consumer_declared', true );
		}
		update_option( $lock, $request_id, false );
		as_schedule_single_action( time() + HOUR_IN_SECONDS, self::CLEANUP_HOOK, array( $lock ), 'ppwb' );
		$this->redirect_to_success( $request_id );
	}

	/**
	 * Redirects to the signed success URL and stops.
	 *
	 * @param int $request_id Request ID.
	 * @return never
	 */
	private function redirect_to_success( int $request_id ): never {
		$value = (string) $request_id;
		wp_safe_redirect( add_query_arg( 'ppwb_done', $value . '.' . $this->tokens->sign( 'done|' . $value ), $this->form_url() ) );
		exit;
	}

	/**
	 * Success view for a signed request reference.
	 *
	 * @param string $reference "ID.signature".
	 * @return array<string, mixed>
	 */
	private function success_view( string $reference ): array {
		$parts = explode( '.', $reference, 2 );
		if ( 2 !== count( $parts ) || ! hash_equals( $this->tokens->sign( 'done|' . $parts[0] ), $parts[1] ) ) {
			return array( 'step' => 'lookup' );
		}

		$summary = $this->requests->find_summary( (int) $parts[0] );
		if ( null === $summary ) {
			return array( 'step' => 'lookup' );
		}

		$submitted = (int) strtotime( $summary['submitted_at_gmt'] . ' UTC' );
		$request   = $this->requests->find( (int) $parts[0] );
		$order     = null === $request ? false : wc_get_order( (int) $request['order_id'] );
		$amount    = null === $request ? '' : wc_price( (float) $request['estimated_total'], array( 'currency' => (string) $request['currency'] ) );
		$method    = '';
		if ( $order instanceof WC_Order ) {
			$method = $this->service->needs_bank_account( $order )
				? __( 'by bank transfer to the account you gave', 'primeplaced-withdrawal-button' )
				/* translators: %s: payment method name. */
				: sprintf( __( 'to the account you paid from (%s)', 'primeplaced-withdrawal-button' ), $order->get_payment_method_title() );
		}

		return array(
			'amount'          => $amount,
			'refund_method'   => $method,
			'pdf_url'         => add_query_arg( 'ppwb_pdf', 1, StatusPage::url_for( (int) $parts[0] ) ),
			'step'            => 'success',
			'request_id'      => (int) $parts[0],
			'number'          => $summary['number'],
			'submitted'       => Dates::datetime( $submitted ),
			'return_address'  => $this->settings->return_address_text(),
			'return_cost'     => $this->settings->return_cost_text(),
			'status_url'      => StatusPage::url_for( (int) $parts[0] ),
			'refund_due'      => Dates::date_gmt( $summary['refund_due_gmt'] ),
			'before_shipment' => in_array( WithdrawalService::BEFORE_SHIPMENT, explode( ',', $summary['flags'] ), true ),
		);
	}

	/**
	 * Loads the order behind a valid token, or returns to step 1.
	 *
	 * @param string                                   $token Step token.
	 * @param callable(WC_Order): array<string, mixed> $next  Step to run.
	 * @return array<string, mixed>
	 */
	private function with_order( string $token, callable $next ): array {
		$data  = $this->tokens->verify( $token );
		$order = null === $data ? false : wc_get_order( $data['order_id'] );

		if ( ! $order instanceof WC_Order || null === $data || strtolower( $order->get_billing_email() ) !== $data['email'] ) {
			return array(
				'step'  => 'lookup',
				'error' => __( 'The form has expired. Please start again.', 'primeplaced-withdrawal-button' ),
			);
		}

		// Every step re-checks the deadline and the order: a form opened in time
		// and sent after the deadline, or a crafted POST, stops here.
		$blocking = $this->service->blocking_reason( $order );
		if ( null !== $blocking ) {
			return $this->blocked_view( $blocking );
		}

		return $next( $order );
	}

	/**
	 * Explains a cancellation before shipment, or '' for a shipped order.
	 *
	 * @param WC_Order $order Order.
	 * @return string
	 */
	private function before_shipment_notice( WC_Order $order ): string {
		if ( ! $this->service->is_before_shipment( $order ) ) {
			return '';
		}

		return sprintf(
			/* translators: %s: order status. */
			__( 'The order status is "%s": we have not shipped it yet. You can cancel it now and we will refund the payment without waiting for a parcel, or withdraw from the contract after you receive it.', 'primeplaced-withdrawal-button' ),
			wc_get_order_status_name( $order->get_status() )
		);
	}

	/**
	 * Message step for an order that cannot be withdrawn now.
	 *
	 * @param array{code: string, deadline?: DateTimeImmutable, status?: string} $blocking Reason from the service.
	 * @return array<string, mixed>
	 */
	private function blocked_view( array $blocking ): array {
		return array(
			'step'    => 'message',
			'title'   => __( 'Withdrawal is not available for this order', 'primeplaced-withdrawal-button' ),
			'message' => $this->blocking_message( $blocking ),
		);
	}

	/**
	 * Lines prepared for templates.
	 *
	 * @param WC_Order                                                                                                                                                 $order Order.
	 * @param list<array{id: int, name: string, ordered: int, available: int, net_minor: int, tax_minor: int, excluded: bool, exclusion_reason: string, note: string}> $lines Service lines.
	 * @return list<array{id: int, name: string, ordered: int, available: int, price: string, excluded: bool, exclusion_reason: string, note: string, variant: string, thumb: string}>
	 */
	private function display_lines( WC_Order $order, array $lines ): array {
		$display = array();
		foreach ( $lines as $line ) {
			$unit    = Money::share( $line['net_minor'] + $line['tax_minor'], 1, $line['ordered'] );
			$item    = $order->get_item( $line['id'] );
			$variant = '';
			$thumb   = '';
			if ( $item instanceof \WC_Order_Item_Product ) {
				$parts = array();
				foreach ( $item->get_formatted_meta_data() as $meta ) {
					$meta    = (array) $meta;
					$parts[] = wp_strip_all_tags( (string) ( $meta['display_key'] ?? '' ) . ': ' . (string) ( $meta['display_value'] ?? '' ) );
				}
				$variant = implode( ', ', $parts );
				$product = $item->get_product();
				$thumb   = $product instanceof \WC_Product ? $product->get_image( 'woocommerce_gallery_thumbnail', array( 'alt' => '' ) ) : '';
			}
			$display[] = array(
				'variant'          => $variant,
				'thumb'            => $thumb,
				'id'               => $line['id'],
				'name'             => $line['name'],
				'ordered'          => $line['ordered'],
				'available'        => $line['available'],
				'excluded'         => $line['excluded'],
				'exclusion_reason' => $line['exclusion_reason'],
				/**
				 * Filters the note shown under a product in the withdrawal form.
				 *
				 * @param string   $note    Note, '' for none.
				 * @param int      $item_id Order item ID.
				 * @param WC_Order $order   Order.
				 */
				'note'             => (string) apply_filters( 'ppwb_form_line_note', $line['note'], $line['id'], $order ),
				'price'            => wc_price( (float) Money::to_decimal( $unit, wc_get_price_decimals() ), array( 'currency' => $order->get_currency() ) ),
			);
		}

		return $display;
	}

	/**
	 * Customer-facing text for a blocking reason.
	 *
	 * @param array{code: string, deadline?: DateTimeImmutable, status?: string} $blocking Reason from the service.
	 * @return string
	 */
	private function blocking_message( array $blocking ): string {
		$contact = (string) get_option( 'woocommerce_email_from_address', get_option( 'admin_email' ) );

		return match ( $blocking['code'] ) {
			'expired'      => sprintf(
				/* translators: 1: deadline date, 2: shop email. */
				__( 'The withdrawal period for this order ended on %1$s. If you think this is a mistake, write to us: %2$s', 'primeplaced-withdrawal-button' ),
				isset( $blocking['deadline'] ) ? Dates::date( $blocking['deadline'] ) : '',
				$contact
			),
			'nothing_left' => __( 'All products from this order are already covered by earlier withdrawal requests or refunds.', 'primeplaced-withdrawal-button' ),
			'only_excluded' => __( 'The products in this order are excluded from the right of withdrawal. If you have questions, contact us.', 'primeplaced-withdrawal-button' ),
			'business'     => sprintf(
				/* translators: %s: shop email. */
				__( 'This order was placed as a business purchase (with a tax ID), so the consumer right of withdrawal does not apply. If you bought as a sole trader with consumer rights, write to us: %s', 'primeplaced-withdrawal-button' ),
				$contact
			),
			'before_shipment' => sprintf(
				/* translators: 1: order status, 2: shop email. */
				__( 'You cannot withdraw from the contract here yet, because the order status is "%1$s". You can do it after you receive the parcel. To cancel the order before shipment, write to us: %2$s', 'primeplaced-withdrawal-button' ),
				$blocking['status'] ?? '',
				$contact
			),
			default        => sprintf(
				/* translators: 1: order status, 2: shop email. */
				__( 'You cannot withdraw from the contract now, because the order status is "%1$s". If you have questions, write to us: %2$s', 'primeplaced-withdrawal-button' ),
				$blocking['status'] ?? '',
				$contact
			),
		};
	}

	/**
	 * Quantities posted in step 2 or carried in step 3.
	 *
	 * @return array<int, int>
	 */
	private function posted_selection(): array {
		// phpcs:ignore WordPress.Security.NonceVerification.Missing, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- Nonce verified in handle(); values cast to int below.
		$raw       = isset( $_POST['ppwb_qty'] ) && is_array( $_POST['ppwb_qty'] ) ? wp_unslash( $_POST['ppwb_qty'] ) : array();
		$selection = array();
		foreach ( (array) $raw as $item_id => $qty ) {
			$selection[ absint( $item_id ) ] = absint( $qty );
		}

		return $selection;
	}

